import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import { pathToFileURL } from 'node:url';
import { verifyPackagedDirectory } from '../release/package-policy.ts';

export interface InstallerOwnedFile {
  readonly path: string;
  readonly bytes: number;
  readonly sha256: string;
}

export interface InstallerOwnedManifest {
  readonly version: 1;
  readonly files: readonly InstallerOwnedFile[];
}

const PACKAGE_ROOT = resolve('release/win-unpacked');
const OUTPUT_ROOT = resolve('release/installer-generated');
const MAX_FILES = 4096;
const MAX_TOTAL_BYTES = 1024 * 1024 * 1024;

export function createInstallerOwnedManifest(
  entries: readonly InstallerOwnedFile[],
): InstallerOwnedManifest {
  if (entries.length === 0 || entries.length > MAX_FILES) throw new Error('安装payload文件数无效');
  const files = entries.map((entry) => ({
    path: normalizeRelativePath(entry.path),
    bytes: checkedBytes(entry.bytes),
    sha256: checkedHash(entry.sha256),
  }));
  if (
    files.some((entry, index) => index > 0 && files[index - 1]!.path >= entry.path) ||
    files.reduce((sum, entry) => sum + entry.bytes, 0) > MAX_TOTAL_BYTES
  )
    throw new Error('安装payload必须排序唯一且在预算内');
  return Object.freeze({
    version: 1,
    files: Object.freeze(files.map((entry) => Object.freeze(entry))),
  });
}

export function renderInstallerBinding(manifest: InstallerOwnedManifest): string {
  const digest = createHash('sha256').update(manifestJson(manifest)).digest('hex');
  return [
    '; Generated by tools/build/installer-generator.ts. Do not edit.',
    `!define AIBROWSE_OWNED_MANIFEST_SHA256 "${digest}"`,
    '!define AIBROWSE_INSTALLER_HELPER "release\\installer-generated\\installer-helper.exe"',
    '!define AIBROWSE_OWNED_MANIFEST "release\\installer-generated\\installer-owned-v1.json"',
    '',
  ].join('\n');
}

export function assertSafeInstallerTemplate(source: string): void {
  for (const required of [
    '!insertmacro AIBROWSE_REJECT_DELETE_APP_DATA',
    '!insertmacro AIBROWSE_HELPER "recover"',
    '!insertmacro AIBROWSE_HELPER "inspect-new"',
    '!insertmacro AIBROWSE_HELPER "commit"',
    '!insertmacro AIBROWSE_HELPER "finalize"',
    'installer-helper.exe" "uninstall"',
  ]) {
    if (!source.includes(required)) throw new Error(`安装脚本缺少固定边界：${required}`);
  }
  if (/RMDir\s+\/r/iu.test(source)) throw new Error('安装脚本禁止递归删除');
  if (/\b(?:cmd|powershell|pwsh|wscript|cscript)\b/iu.test(source))
    throw new Error('安装脚本禁止通用命令解释器');
}

const collectPackageFiles = (root: string): InstallerOwnedFile[] => {
  const files: InstallerOwnedFile[] = [];
  const visit = (directory: string): void => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isSymbolicLink()) throw new Error('安装payload禁止链接');
      if (entry.isDirectory()) visit(path);
      else if (entry.isFile()) {
        const bytes = readFileSync(path);
        files.push({
          path: relative(root, path).split(sep).join('/'),
          bytes: bytes.length,
          sha256: createHash('sha256').update(bytes).digest('hex'),
        });
      } else throw new Error('安装payload含未知文件类型');
    }
  };
  visit(root);
  return files.sort((left, right) =>
    left.path < right.path ? -1 : left.path > right.path ? 1 : 0,
  );
};

const main = async (): Promise<void> => {
  if (process.argv.length !== 2) throw new Error('安装生成器不接受路径参数');
  await verifyPackagedDirectory(PACKAGE_ROOT);
  const manifest = createInstallerOwnedManifest(collectPackageFiles(PACKAGE_ROOT));
  const template = readFileSync(resolve('tools/build/installer-template.nsi'), 'utf8');
  assertSafeInstallerTemplate(template);
  mkdirSync(OUTPUT_ROOT, { recursive: false });
  const manifestPath = join(OUTPUT_ROOT, 'installer-owned-v1.json');
  const bindingPath = join(OUTPUT_ROOT, 'installer-binding.nsh');
  const serializedManifest = manifestJson(manifest);
  const manifestSha256 = createHash('sha256').update(serializedManifest).digest('hex');
  writeFileSync(manifestPath, serializedManifest, { flag: 'wx' });
  writeFileSync(bindingPath, renderInstallerBinding(manifest), { flag: 'wx' });
  const generatedHelperSource = join(OUTPUT_ROOT, 'installer-helper.generated.cs');
  const helperSource = readFileSync(resolve('tools/build/installer-helper.cs'), 'utf8');
  if (!helperSource.includes('__AIBROWSE_MANIFEST_SHA256__'))
    throw new Error('installer helper缺少manifest绑定占位符');
  writeFileSync(
    generatedHelperSource,
    helperSource.replaceAll('__AIBROWSE_MANIFEST_SHA256__', manifestSha256),
    { flag: 'wx' },
  );
  const compiler = join(process.env.WINDIR ?? '', 'Microsoft.NET/Framework64/v4.0.30319/csc.exe');
  if (!statSync(compiler, { throwIfNoEntry: false })?.isFile())
    throw new Error('现有.NET Framework C#编译器不可用');
  execFileSync(
    compiler,
    [
      '/nologo',
      '/target:exe',
      '/platform:x64',
      '/optimize+',
      `/out:${join(OUTPUT_ROOT, 'installer-helper.exe')}`,
      '/reference:System.Web.Extensions.dll',
      generatedHelperSource,
    ],
    { cwd: resolve('.'), windowsHide: true, stdio: 'pipe' },
  );
};

function normalizeRelativePath(value: string): string {
  if (
    value.length === 0 ||
    value.length > 260 ||
    value.includes('\\') ||
    value.includes(':') ||
    value.startsWith('/') ||
    value.split('/').some((part) => part === '' || part === '.' || part === '..')
  )
    throw new Error('安装payload路径无效');
  return value;
}

function manifestJson(manifest: InstallerOwnedManifest): string {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}
function checkedBytes(value: number): number {
  if (!Number.isSafeInteger(value) || value < 1) throw new Error('安装payload长度无效');
  return value;
}
function checkedHash(value: string): string {
  if (!/^[0-9a-f]{64}$/u.test(value)) throw new Error('安装payload摘要无效');
  return value;
}

const invoked = process.argv[1] === undefined ? null : pathToFileURL(resolve(process.argv[1])).href;
if (invoked === import.meta.url) {
  void main().catch((error: unknown) => {
    process.stderr.write(`${error instanceof Error ? error.message : '未知错误'}\n`);
    process.exitCode = 1;
  });
}
